/**
 * Regenerates `src/build/poetry-requirements.ts`: Poetry, the tool that
 * installs a Poetry-locked Python pack in its image, pinned with every
 * dependency by hash (`uv pip compile --universal --generate-hashes`, for
 * the image's Python). The Containerfile installs it with
 * `--require-hashes`, so a build gets exactly these files.
 *
 *   node scripts/gen-poetry-requirements.mjs [<poetry version>]
 *
 * Needs `uv` on PATH and the network (PyPI).
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'build', 'poetry-requirements.ts');

const current = /POETRY_VERSION = '([^']+)'/.exec(readFileSync(target, 'utf8'))?.[1];
const version = process.argv[2] ?? current;
if (version === undefined)
  throw new Error('give a Poetry version: gen-poetry-requirements.mjs <version>');

const requirements = execFileSync(
  'uv',
  [
    'pip',
    'compile',
    '-',
    '--universal',
    '--generate-hashes',
    '--python-version',
    '3.13',
    '--no-header',
    '--quiet',
  ],
  { input: `poetry==${version}\n`, encoding: 'utf8' },
);

writeFileSync(
  target,
  `// SPDX-License-Identifier: Apache-2.0
// Copyright (C) 2026 Kindgi Inc.

// Generated by scripts/gen-poetry-requirements.mjs — do not edit.

/** The Poetry a Poetry-locked Python pack's image installs with. */
export const POETRY_VERSION = '${version}';

/** Poetry and its dependencies, pinned by hash (\`pip install --require-hashes\`). */
export const POETRY_REQUIREMENTS = ${JSON.stringify(requirements)};
`,
);
console.log(
  `wrote ${target} — poetry==${version}, ${requirements.split('\n').filter((l) => /^[a-z]/.test(l)).length} packages`,
);
