# ---------------------------------------------------------------------------
# Names
# ---------------------------------------------------------------------------


def snake(name: str) -> str:
    out = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).replace("-", "_").lower()
    return f"{out}_" if keyword.iskeyword(out) else out


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[._\-]", name) if part)


# ---------------------------------------------------------------------------
# The operation table
# ---------------------------------------------------------------------------


@dataclass
class Param:
    name: str  # on the wire
    py: str  # in Python
    where: str  # path | query | header
    required: bool
    annotation: str
    description: str
    encode: str | None = None  # a `_base` helper that writes the wire value


@dataclass
class Operation:
    id: str
    method: str
    path: str
    summary: str
    description: str
    params: list[Param]
    body: str | None  # model class name
    body_kind: str | None  # json | multipart
    response: str | None  # model class name
    response_kind: str  # json | sse | binary | empty
    status: int
    # When the 2xx answers carry different models: each status's model
    # class name (`secrets.rotate`: 201 sync, 202 async). Empty otherwise.
    responses: dict[int, str] = field(default_factory=dict)
    follow: bool = False  # a FOLLOWS method: `_follow`, not `_stream`

    @property
    def resource(self) -> tuple[str, ...]:
        return tuple(self.id.split(".")[:-1])

    @property
    def name(self) -> str:
        return snake(self.id.split(".")[-1])


@dataclass
class Resource:
    path: tuple[str, ...]
    operations: list[Operation] = field(default_factory=list)
    children: dict[str, Resource] = field(default_factory=dict)

    @property
    def class_name(self) -> str:
        return "".join(pascal(p) for p in self.path) + "Resource"


def deref(doc: dict[str, Any], schema: dict[str, Any]) -> dict[str, Any]:
    while "$ref" in schema:
        schema = doc["components"]["schemas"][schema["$ref"].split("/")[-1]]
    return schema


ID_PARAM = re.compile(r"(?:^id|Id)$")


def param_annotation(doc: dict[str, Any], schema: dict[str, Any], name: str = "") -> str:
    resolved = deref(doc, schema)
    if "enum" in resolved:
        return "Literal[" + ", ".join(json.dumps(v) for v in resolved["enum"]) + "]"
    kind = resolved.get("type")
    if kind == "array":
        # A repeated query parameter (`segment=a&segment=b`): httpx repeats a list's
        # key. One value is one too, so a parameter that took one before still does.
        item = param_annotation(doc, resolved.get("items", {}), name)
        return f"{item} | list[{item}]"
    if kind == "string" and (resolved.get("format") == "uuid" or ID_PARAM.search(name)):
        # An id: the models carry ids as `UUID` (`format: uuid`), so a model's
        # id passes straight back in (`client.runs.get(run.id)`); it's sent as text.
        return "str | UUID"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}.get(
        kind if isinstance(kind, str) else "", "Any"
    )


def hoist(doc: dict[str, Any], schema: dict[str, Any], name: str) -> str:
    """The component name for `schema`, adding it to the components when inline."""
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    components = doc["components"]["schemas"]
    if name in components:
        raise SystemExit(f"gen_client: hoisted name {name} collides with a component")
    components[name] = schema
    return name


# More Python names for an operation, generated beside its own: the name
# the other resources use for the same call, so the client's names line
# up (`test_sets.unregister`, as `agents.unregister`).
ALIASES: dict[str, tuple[str, ...]] = {
    "testSets.versions.unregister": ("testSets.unregister",),
}

# A run stream's follow method, generated beside it: the same call, through
# to the run's terminal event. The server ends a run's stream after 5 minutes
# while the run goes on; `_follow` reconnects after the last event. Named as
# the Java client names them (`runs().follow`, `runs().followProgress`).
FOLLOWS: dict[str, tuple[str, str]] = {
    "runs.stream": ("runs.follow", "Follow a run's events to its end"),
    "runs.progressStream": ("runs.followProgress", "Follow a run's progress to its end"),
}
FOLLOW_DESCRIPTION = (
    "`{stream}`, through to the run's terminal event (`run.completed`, `run.failed` or "
    "`run.cancelled`), each event once. The server ends a run's stream after 5 minutes "
    "while the run goes on; this reconnects with `Last-Event-Id` and goes on. A dropped "
    "connection, a 429 or a 502-504 is retried with backoff; any other error is raised. "
    "Ends after the terminal event."
)


def operations(source: dict[str, Any]) -> tuple[dict[str, Any], list[Operation]]:
    doc = copy.deepcopy(source)
    ops: list[Operation] = []
    for path, item in doc["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if op is None:
                continue
            op_id: str = op["operationId"]
            if op.get("x-kindgi-sender-only"):
                # An outside sender's path (the inbound webhook receiver), not a client's.
                continue
            params: list[Param] = []
            for raw in [*item.get("parameters", []), *op.get("parameters", [])]:
                p = deref(doc, raw) if "$ref" in raw else raw
                py = {"Idempotency-Key": "idempotency_key", "Last-Event-Id": "last_event_id"}.get(
                    p["name"], snake(p["name"].removeprefix("X-").replace("-", "_"))
                )
                if p.get("x-kindgi-segment-path"):
                    # A segment path: `{key, value}` steps, as TypeScript and
                    # `runs.start` take it, written as repeated `key:value`.
                    params.append(
                        Param(
                            name=p["name"],
                            py="segments",
                            where=p["in"],
                            required=bool(p.get("required", False)),
                            annotation="Sequence[_models.ScopeSegment | Mapping[str, str]]",
                            description=p.get("description", ""),
                            encode="_segments",
                        )
                    )
                    continue
                params.append(
                    Param(
                        name=p["name"],
                        py=py,
                        where=p["in"],
                        required=bool(p.get("required", p["in"] == "path")),
                        annotation=param_annotation(doc, p.get("schema", {}), p["name"]),
                        description=p.get("description", ""),
                    )
                )
            # Path parameters in template order.
            order = re.findall(r"{([^}]+)}", path)
            params.sort(
                key=lambda p: (p.where != "path", order.index(p.name) if p.name in order else 0)
            )

            body = body_kind = None
            request = op.get("requestBody")
            if request is not None:
                content = request["content"]
                if "application/json" in content:
                    body_kind = "json"
                    body = hoist(doc, content["application/json"]["schema"], pascal(op_id) + "Body")
                elif "multipart/form-data" in content:
                    body_kind = "multipart"

            status, response, response_kind = 204, None, "empty"
            for code, answer in sorted(op.get("responses", {}).items()):
                if not code.startswith("2"):
                    continue
                status = int(code)
                content = answer.get("content", {})
                if "text/event-stream" in content:
                    response_kind = "sse"
                    response = hoist(
                        doc, content["text/event-stream"]["schema"], pascal(op_id) + "Event"
                    )
                elif "application/json" in content:
                    response_kind = "json"
                    response = hoist(
                        doc, content["application/json"]["schema"], pascal(op_id) + "Response"
                    )
                elif content:
                    response_kind = "binary"
                break
            # The client picks the model by status when the 2xx answers differ,
            # as the Java client does; otherwise every 2xx is the first's model.
            responses: dict[int, str] = {}
            if response_kind == "json":
                answers = op.get("responses", {})
                first = answers[str(status)]["content"]["application/json"]["schema"]
                for code, answer in sorted(answers.items()):
                    schema = answer.get("content", {}).get("application/json", {}).get("schema")
                    if code.startswith("2") and int(code) != status and schema not in (None, first):
                        responses[int(code)] = hoist(doc, schema, f"{pascal(op_id)}Response{code}")
                if responses:
                    assert response is not None
                    responses = {status: response, **responses}
            ops.append(
                Operation(
                    id=op_id,
                    method=method.upper(),
                    path=path,
                    summary=op.get("summary", "").strip(),
                    description=op.get("description", "").strip(),
                    params=params,
                    body=body,
                    body_kind=body_kind,
                    response=response,
                    response_kind=response_kind,
                    status=status,
                    responses=responses,
                )
            )
    ops += [replace(op, id=alias) for op in list(ops) for alias in ALIASES.get(op.id, ())]
    ops += [
        replace(
            op,
            id=FOLLOWS[op.id][0],
            follow=True,
            summary=FOLLOWS[op.id][1],
            description=FOLLOW_DESCRIPTION.format(stream=snake_path(op.id)),
        )
        for op in list(ops)
        if op.id in FOLLOWS
    ]
    return doc, ops


def snake_path(op_id: str) -> str:
    """`runs.progressStream` → `runs.progress_stream`, as the client names it."""
    return ".".join(snake(part) for part in op_id.split("."))


def tree(ops: list[Operation]) -> Resource:
    root = Resource(path=())
    for op in ops:
        node = root
        for depth in range(1, len(op.resource) + 1):
            segment = op.resource[depth - 1]
            node = node.children.setdefault(segment, Resource(path=op.resource[:depth]))
        node.operations.append(op)
    return root


