  private TypeSpec enumClass(Ir.EnumDecl d) {
    ClassName cn = d.name();
    ClassName valueEnum = cn.nestedClass(cn.simpleNames().contains("Value") ? "Known" : "Value");
    TypeSpec.Builder tb =
        TypeSpec.classBuilder(cn)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc(
                "$L$L\n",
                Docs.javadoc(d.description()).isEmpty() ? "" : Docs.javadoc(d.description()) + "\n\n<p>",
                "One of the values below, or one this client doesn't know yet: {@link #of} keeps any value,"
                    + " and {@link #value()} is {@code UNRECOGNIZED} for an unknown one. Switch on {@link #value()}.");
    TypeSpec.Builder ve =
        TypeSpec.enumBuilder(valueEnum)
            .addModifiers(Modifier.PUBLIC)
            .addJavadoc("The values this client knows, and {@code UNRECOGNIZED}.\n");
    Set<String> constants = new HashSet<>();
    CodeBlock.Builder known = CodeBlock.builder().add("$T.ofEntries(", Map.class);
    int i = 0;
    for (String v : d.values()) {
      String c = Names.constant(v);
      if (c.equals("UNRECOGNIZED") || !constants.add(c)) {
        throw new GenerationException(cn + ": enum value \"" + v + "\" makes a duplicate constant " + c);
      }
      ve.addEnumConstant(c);
      tb.addField(
          FieldSpec.builder(cn, c, Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
              .addJavadoc("<code>$L</code>\n", Docs.javadoc(v))
              .initializer("new $T($S, $T.$L)", cn, v, valueEnum, c)
              .build());
      known.add(i++ == 0 ? "\n$>$T.entry($S, $L)" : ",\n$T.entry($S, $L)", Map.class, v, c);
    }
    known.add("$<)");
    ve.addEnumConstant("UNRECOGNIZED");
    TypeName mapType = ParameterizedTypeName.get(ModelPlanner.MAP, ModelPlanner.STRING, cn);
    tb.addField(FieldSpec.builder(mapType, "byValue", Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL).initializer(known.build()).build());
    tb.addField(ModelPlanner.STRING, "raw", Modifier.PRIVATE, Modifier.FINAL);
    tb.addField(valueEnum, "value", Modifier.PRIVATE, Modifier.FINAL);
    tb.addMethod(
        MethodSpec.constructorBuilder()
            .addModifiers(Modifier.PRIVATE)
            .addParameter(ModelPlanner.STRING, "raw")
            .addParameter(valueEnum, "value")
            .addStatement("this.raw = raw")
            .addStatement("this.value = value")
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("of")
            .addJavadoc("The value for this text: a known constant, or an unrecognized value that keeps it.\n")
            .addAnnotation(JSON_CREATOR)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(cn)
            .addParameter(ModelPlanner.STRING, "raw")
            .addStatement("$T known = byValue.get($T.requireNonNull(raw, $S))", cn, Objects.class, "raw")
            .addStatement("return known != null ? known : new $T(raw, $T.UNRECOGNIZED)", cn, valueEnum)
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("asString")
            .addJavadoc("The value as the API spells it.\n")
            .addAnnotation(JSON_VALUE)
            .addModifiers(Modifier.PUBLIC)
            .returns(ModelPlanner.STRING)
            .addStatement("return raw")
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("value")
            .addJavadoc("Which known value this is, or {@code UNRECOGNIZED}.\n")
            .addModifiers(Modifier.PUBLIC)
            .returns(valueEnum)
            .addStatement("return value")
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("isKnown")
            .addJavadoc("Whether this client knows the value.\n")
            .addModifiers(Modifier.PUBLIC)
            .returns(TypeName.BOOLEAN)
            .addStatement("return value != $T.UNRECOGNIZED", valueEnum)
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("equals")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(TypeName.BOOLEAN)
            .addParameter(Object.class, "other")
            .addStatement("return other instanceof $T && (($T) other).raw.equals(raw)", cn, cn)
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("hashCode")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(TypeName.INT)
            .addStatement("return raw.hashCode()")
            .build());
    tb.addMethod(
        MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(ModelPlanner.STRING)
            .addStatement("return raw")
            .build());
    if (cn.enclosingClassName() != null) {
      tb.addModifiers(Modifier.STATIC);
    }
    tb.addType(ve.build());
    return tb.build();
  }

