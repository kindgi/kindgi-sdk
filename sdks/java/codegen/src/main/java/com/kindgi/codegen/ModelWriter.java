  private TypeSpec union(Ir.UnionDecl u) {
    ClassName cn = u.name;
    TypeSpec.Builder ib = TypeSpec.interfaceBuilder(cn).addModifiers(modifiers(cn)).addModifiers(Modifier.SEALED).addSuperinterface(MODEL);
    StringBuilder doc = new StringBuilder(Docs.javadoc(u.description));
    if (doc.length() > 0) {
      doc.append("\n\n<p>");
    }
    doc.append("One of:\n<ul>\n");
    for (Ir.Variant v : u.variants) {
      doc.append("<li>{@link ").append(String.join(".", v.type().simpleNames())).append("}");
      if (v.tags() != null) {
        doc.append(": {@code ").append(u.tagWire).append("} is ").append(String.join(" or ", v.tags().stream().map(t -> "<code>" + Docs.javadoc(t) + "</code>").toList()));
      } else if (v.text()) {
        doc.append(": text").append(v.allowed() == null ? "" : ", <code>" + Docs.javadoc(String.join("|", v.allowed())) + "</code>");
      } else if (v.uniqueRequired() != null) {
        doc.append(": has {@code ").append(v.uniqueRequired().get(0)).append("}");
      }
      doc.append("</li>\n");
      ib.addPermittedSubclass(v.type());
    }
    if (u.unrecognized != null) {
      doc.append("<li>{@link ").append(u.unrecognized.simpleName()).append("}: a variant this client doesn't know yet, kept as it came</li>\n");
      ib.addPermittedSubclass(u.unrecognized);
    }
    doc.append("</ul>");
    ib.addJavadoc("$L\n", doc.toString());

    boolean tagged = u.kind == Ir.UnionKind.TAGGED;
    if (tagged) {
      ib.addMethod(
          MethodSpec.methodBuilder(u.tagJava)
              .addJavadoc("The {@code $L} that tells the variants apart.\n", u.tagWire)
              .addModifiers(Modifier.PUBLIC, Modifier.ABSTRACT)
              .returns(ModelPlanner.STRING)
              .build());
    }
    if (u.kind == Ir.UnionKind.TAGGED || u.kind == Ir.UnionKind.DEDUCED) {
      AnnotationSpec.Builder info = AnnotationSpec.builder(JSON_TYPE_INFO);
      if (tagged) {
        info.addMember("use", "$T.Id.NAME", JSON_TYPE_INFO)
            .addMember("include", "$T.As.EXISTING_PROPERTY", JSON_TYPE_INFO)
            .addMember("property", "$S", u.tagWire)
            .addMember("visible", "true");
      } else {
        info.addMember("use", "$T.Id.DEDUCTION", JSON_TYPE_INFO);
      }
      info.addMember("defaultImpl", "$T.class", u.unrecognized);
      ib.addAnnotation(info.build());
      AnnotationSpec.Builder subs = AnnotationSpec.builder(JSON_SUB_TYPES);
      for (Ir.Variant v : u.variants) {
        AnnotationSpec.Builder t = AnnotationSpec.builder(JSON_SUB_TYPES.nestedClass("Type")).addMember("value", "$T.class", v.type());
        if (tagged) {
          if (v.tags().size() == 1) {
            t.addMember("name", "$S", v.tags().get(0));
          } else {
            t.addMember("names", "$L", stringArray(v.tags()));
          }
        }
        subs.addMember("value", "$L", t.build());
      }
      ib.addAnnotation(subs.build());
    }
    if (u.unrecognized != null) {
      ib.addType(unrecognized(u));
    }
    if (u.kind == Ir.UnionKind.TEXT_OR_OBJECT) {
      Ir.Variant text = u.textVariant();
      ib.addMethod(
          MethodSpec.methodBuilder("of")
              .addJavadoc("The text variant.\n")
              .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
              .returns(cn)
              .addParameter(ModelPlanner.STRING, "text")
              .addStatement("return new $T(text)", text.type())
              .build());
      if (text.allowed() != null && text.allowed().size() == 1) {
        ib.addField(
            FieldSpec.builder(text.type(), Names.constant(text.allowed().get(0)), Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
                .addJavadoc("<code>$L</code>\n", Docs.javadoc(text.allowed().get(0)))
                .initializer("new $T($S)", text.type(), text.allowed().get(0))
                .build());
      }
      ib.addType(textVariant(u, text));
    }
    for (Ir.Decl n : u.nested) {
      ib.addType(type(n));
    }
    return ib.build();
  }

  private static CodeBlock stringArray(List<String> values) {
    CodeBlock.Builder b = CodeBlock.builder().add("{");
    for (int i = 0; i < values.size(); i++) {
      b.add(i == 0 ? "$S" : ", $S", values.get(i));
    }
    return b.add("}").build();
  }

  private TypeSpec unrecognized(Ir.UnionDecl u) {
    MethodSpec.Builder ctor = MethodSpec.compactConstructorBuilder().addModifiers(Modifier.PUBLIC);
    TypeName props = ParameterizedTypeName.get(ModelPlanner.MAP, ModelPlanner.STRING, ModelPlanner.OBJECT);
    String tag = u.tagWire != null && u.objectKind == Ir.UnionKind.TAGGED ? u.tagWire : null;
    if (tag != null) {
      ctor.addParameter(
          ParameterSpec.builder(nullable(ModelPlanner.STRING), u.tagJava)
              .addAnnotation(AnnotationSpec.builder(JSON_PROPERTY).addMember("value", "$S", tag).build())
              .build());
    }
    ctor.addParameter(ParameterSpec.builder(props, "properties").addAnnotation(JSON_ANY_SETTER).addAnnotation(JSON_ANY_GETTER).build());
    ctor.addStatement("properties = $T.extras(properties)", CHECKS);
    TypeSpec.Builder rb = TypeSpec.recordBuilder(u.unrecognized);
    return rb
        .addModifiers(modifiers(u.unrecognized))
        .addAnnotation(AnnotationSpec.builder(JSON_INCLUDE).addMember("value", "$T.Include.NON_NULL", JSON_INCLUDE).build())
        .addSuperinterface(u.name)
        .addJavadoc(
            "A variant this client doesn't know yet (a newer runtime's), kept as it came.\n\n"
                + (tag != null ? "@param $N its {@code $L}\n" : "$L$L")
                + "@param properties its other properties\n",
            tag != null ? u.tagJava : "",
            tag != null ? tag : "")
        .recordConstructor(ctor.build())
        .addMethod(
            MethodSpec.methodBuilder("validate")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .addParameter(CHECKS, "checks")
                .addComment("Nothing to check: the client doesn't know this variant's constraints.")
                .build())
        .build();
  }

  private TypeSpec textVariant(Ir.UnionDecl u, Ir.Variant text) {
    MethodSpec ctor =
        MethodSpec.compactConstructorBuilder()
            .addModifiers(Modifier.PUBLIC)
            .addParameter(ParameterSpec.builder(ModelPlanner.STRING, "value").addAnnotation(JSON_VALUE).build())
            .addStatement("$T.requireNonNull(value, $S)", Objects.class, String.join(".", u.name.simpleNames()) + " text")
            .build();
    MethodSpec.Builder validate =
        MethodSpec.methodBuilder("validate")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(CHECKS, "checks");
    if (text.allowed() != null) {
      validate.addStatement("checks.oneOf($S, value, $L)", "", stringList(text.allowed()));
    }
    return TypeSpec.recordBuilder(text.type())
        .addModifiers(modifiers(text.type()))
        .addSuperinterface(u.name)
        .addJavadoc("The text variant.\n\n@param value the text\n")
        .recordConstructor(ctor)
        .addMethod(validate.build())
        .build();
  }
