  private TypeSpec record(Ir.RecordDecl d) {
    ClassName cn = d.name;
    TypeSpec.Builder rb = TypeSpec.recordBuilder(cn).addModifiers(modifiers(cn));
    List<String> params = new ArrayList<>();
    rb.addAnnotation(
        AnnotationSpec.builder(JSON_INCLUDE).addMember("value", "$T.Include.NON_NULL", JSON_INCLUDE).build());
    if (d.interfaces.isEmpty()) {
      rb.addSuperinterface(MODEL);
    }
    for (ClassName i : d.interfaces) {
      rb.addSuperinterface(i);
    }
    String owner = String.join(".", cn.simpleNames());
    MethodSpec.Builder ctor = MethodSpec.compactConstructorBuilder().addModifiers(Modifier.PUBLIC);
    CodeBlock.Builder checks = CodeBlock.builder();
    PatternNames patterns = new PatternNames();
    for (Ir.Field f : d.fields) {
      ParameterSpec.Builder p = ParameterSpec.builder(componentType(f), f.java);
      p.addAnnotation(AnnotationSpec.builder(JSON_PROPERTY).addMember("value", "$S", f.wire).build());
      if (f.triState) {
        p.addAnnotation(
            AnnotationSpec.builder(JSON_INCLUDE)
                .addMember("value", "$T.Include.CUSTOM", JSON_INCLUDE)
                .addMember("valueFilter", "$T.AbsentFilter.class", OPTIONAL_NULLABLE)
                .build());
      }
      ctor.addParameter(p.build());
      String path = owner + "." + f.wire;
      if (f.tagValues != null && f.tagValues.size() == 1) {
        ctor.addStatement("$N = $T.constant($N, $S, $S)", f.java, CHECKS, f.java, f.tagValues.get(0), path);
      } else if (f.constValue != null) {
        ctor.addStatement("$N = $T.constant($N, $L, $S)", f.java, CHECKS, f.java, literal(f.constValue), path);
      } else if (f.triState) {
        ctor.addStatement("$N = $T.triState($N)", f.java, CHECKS, f.java);
      } else if (f.required && !f.nullable) {
        ctor.addStatement("$N = $T.required($N, $S)", f.java, CHECKS, f.java, path);
      }
      if (!f.triState) {
        TypeName raw = f.type;
        if (raw instanceof ParameterizedTypeName && ((ParameterizedTypeName) raw).rawType().equals(ModelPlanner.LIST)) {
          ctor.addStatement("$N = $T.list($N)", f.java, CHECKS, f.java);
        } else if (raw instanceof ParameterizedTypeName && ((ParameterizedTypeName) raw).rawType().equals(ModelPlanner.MAP)) {
          ctor.addStatement("$N = $T.map($N)", f.java, CHECKS, f.java);
        }
      }
      String value = f.triState ? f.java + ".orElse(null)" : f.java;
      if (f.tagValues != null && f.tagValues.size() > 1) {
        checks.addStatement("checks.oneOf($S, $N, $L)", f.wire, f.java, stringList(f.tagValues));
      }
      constraintChecks(checks, rb, patterns, f.wire, value, f.type, f.constraints);
      if (mentionsModel(f.type)) {
        checks.addStatement("checks.nested($S, $L)", f.wire, value);
      }
      String fieldDoc = fieldDoc(f);
      if (!fieldDoc.isEmpty()) {
        params.add("@param " + f.java + " " + fieldDoc);
      }
    }
    if (d.open) {
      TypeName mapType = ParameterizedTypeName.get(ModelPlanner.MAP, ModelPlanner.STRING, d.openValueType);
      ctor.addParameter(
          ParameterSpec.builder(mapType, "additionalProperties")
              .addAnnotation(JSON_ANY_SETTER)
              .addAnnotation(JSON_ANY_GETTER)
              .build());
      ctor.addStatement("additionalProperties = $T.extras(additionalProperties)", CHECKS);
      params.add("@param additionalProperties properties this client doesn't know, kept as they came");
    }
    rb.recordConstructor(ctor.build());
    String description = Docs.javadoc(d.description);
    String doc = description + (description.isEmpty() || params.isEmpty() ? "" : "\n\n") + String.join("\n", params);
    if (!doc.isEmpty()) {
      rb.addJavadoc("$L\n", doc);
    }
    rb.addMethod(
        MethodSpec.methodBuilder("validate")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(CHECKS, "checks")
            .addCode(checks.build())
            .build());
    builder(rb, d);
    for (Ir.Decl n : d.nested) {
      rb.addType(type(n));
    }
    return rb.build();
  }

  /** {@code public}, and {@code static} for a nested type (JavaPoet asks for it in an interface). */
  static Modifier[] modifiers(ClassName cn) {
    return cn.enclosingClassName() == null
        ? new Modifier[] {Modifier.PUBLIC}
        : new Modifier[] {Modifier.PUBLIC, Modifier.STATIC};
  }

  /** A component's declared type: tri-state, required, or nullable. */
  private TypeName componentType(Ir.Field f) {
    if (f.triState) {
      return ParameterizedTypeName.get(OPTIONAL_NULLABLE, f.type);
    }
    if (f.required && !f.nullable) {
      return f.type;
    }
    return nullable(f.type);
  }

  private static TypeName nullable(TypeName t) {
    if (t instanceof ArrayTypeName) {
      return t;
    }
    return t.annotated(AnnotationSpec.builder(NULLABLE).build());
  }

  private String fieldDoc(Ir.Field f) {
    String text = Docs.javadoc(f.description);
    List<String> notes = new ArrayList<>();
    if (f.required && !f.nullable && f.constValue == null && f.tagValues == null) {
      notes.add("Required.");
    }
    if (f.triState) {
      notes.add("Absent, an explicit {@code null}, or a value.");
    }
    if (f.defaultValue != null) {
      notes.add("Defaults to <code>" + Docs.javadoc(String.valueOf(f.defaultValue)) + "</code> on the server.");
    }
    if (f.constValue != null) {
      notes.add("Always <code>" + Docs.javadoc(String.valueOf(f.constValue)) + "</code>.");
    }
    String joined = String.join(" ", notes);
    if (text.isEmpty()) {
      return joined;
    }
    return joined.isEmpty() ? text : text + (text.endsWith(".") ? " " : ". ") + joined;
  }

  private void builder(TypeSpec.Builder rb, Ir.RecordDecl d) {
    ClassName cn = d.name;
    ClassName bn = cn.nestedClass("Builder");
    TypeSpec.Builder b =
        TypeSpec.classBuilder(bn)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
            .addJavadoc("Builds a {@link $T}; {@link #build()} checks it against the API's constraints.\n", cn);
    MethodSpec.Builder copy = MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).addParameter(cn, "source");
    List<String> args = new ArrayList<>();
    for (Ir.Field f : d.fields) {
      TypeName ft = componentType(f);
      FieldSpec.Builder field = FieldSpec.builder(ft, f.java, Modifier.PRIVATE);
      if (f.triState) {
        field.initializer("$T.absent()", OPTIONAL_NULLABLE);
      } else if (f.tagValues != null && f.tagValues.size() == 1) {
        field.initializer("$S", f.tagValues.get(0));
      } else if (f.constValue != null) {
        field.initializer("$L", literal(f.constValue));
      } else if (f.required && planner.index.get(f.type) instanceof Ir.EnumDecl
          && ((Ir.EnumDecl) planner.index.get(f.type)).values().size() == 1) {
        // A required enum with one value: the builder starts with it.
        field.initializer("$T.$L", f.type, Names.constant(((Ir.EnumDecl) planner.index.get(f.type)).values().get(0)));
      }
      b.addField(field.build());
      copy.addStatement("this.$N = source.$N", f.java, f.java);
      args.add(f.java);
      boolean fixed = f.constValue != null || (f.tagValues != null && f.tagValues.size() == 1);
      if (fixed) {
        continue;
      }
      String fdoc = fieldDoc(f);
      if (f.triState) {
        b.addMethod(
            setter(bn, f.java, nullable(f.type), fdoc + (fdoc.isEmpty() ? "" : "\n<p>") + "A {@code null} sends an explicit {@code null}.")
                .addStatement("this.$N = $T.of($N)", f.java, OPTIONAL_NULLABLE, f.java)
                .addStatement("return this")
                .build());
      } else {
        b.addMethod(
            setter(bn, f.java, ft, fdoc).addStatement("this.$N = $N", f.java, f.java).addStatement("return this").build());
      }
      Ir.UnionDecl textUnion = textUnion(f.type);
      if (textUnion != null) {
        Ir.Variant text = textUnion.textVariant();
        CodeBlock wrap = CodeBlock.of("new $T($N)", text.type(), f.java);
        b.addMethod(
            setter(bn, f.java, ModelPlanner.STRING, "The text form of {@link #" + f.java + "(" + textUnion.name.simpleName() + ")}.")
                .addStatement(
                    f.triState ? "this.$N = $T.of($L)" : "this.$N = $L",
                    f.triState ? new Object[] {f.java, OPTIONAL_NULLABLE, wrap} : new Object[] {f.java, wrap})
                .addStatement("return this")
                .build());
      }
    }
    if (d.open) {
      TypeName mapType = ParameterizedTypeName.get(ClassName.get(LinkedHashMap.class), ModelPlanner.STRING, d.openValueType);
      b.addField(FieldSpec.builder(mapType, "additionalProperties", Modifier.PRIVATE).initializer("new $T<>()", LinkedHashMap.class).build());
      copy.addStatement("this.additionalProperties.putAll(source.additionalProperties())");
      args.add("additionalProperties");
      b.addMethod(
          MethodSpec.methodBuilder("putAdditionalProperty")
              .addJavadoc("Adds a property beside the known ones.\n")
              .addModifiers(Modifier.PUBLIC)
              .returns(bn)
              .addParameter(ModelPlanner.STRING, "key")
              .addParameter(nullable(d.openValueType), "value")
              .addStatement("this.additionalProperties.put($T.requireNonNull(key, $S), value)", Objects.class, "key")
              .addStatement("return this")
              .build());
    }
    b.addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
    b.addMethod(copy.build());
    b.addMethod(
        MethodSpec.methodBuilder("build")
            .addJavadoc("The {@link $T}.\n\n@return the value\n@throws $T when it breaks the API's constraints (every problem is listed)\n", cn, ClassName.get(MODELS, "ValidationException"))
            .addModifiers(Modifier.PUBLIC)
            .returns(cn)
            .addStatement("$T built = new $T($L)", cn, cn, String.join(", ", args))
            .addStatement("built.validate()")
            .addStatement("return built")
            .build());
    rb.addType(b.build());
    rb.addMethod(
        MethodSpec.methodBuilder("builder")
            .addJavadoc("A builder for a {@link $T}.\n\n@return the builder\n", cn)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(bn)
            .addStatement("return new $T()", bn)
            .build());
    rb.addMethod(
        MethodSpec.methodBuilder("toBuilder")
            .addJavadoc("A builder that starts from this value.\n\n@return the builder\n")
            .addModifiers(Modifier.PUBLIC)
            .returns(bn)
            .addStatement("return new $T(this)", bn)
            .build());
  }

  private static MethodSpec.Builder setter(ClassName builder, String name, TypeName type, String doc) {
    MethodSpec.Builder m =
        MethodSpec.methodBuilder(name).addModifiers(Modifier.PUBLIC).returns(builder).addParameter(type, name);
    if (!doc.isEmpty()) {
      m.addJavadoc("$L\n", doc);
    }
    return m;
  }

  private Ir.UnionDecl textUnion(TypeName t) {
    if (t instanceof ClassName) {
      Ir.Decl d = planner.index.get(t);
      if (d instanceof Ir.UnionDecl && ((Ir.UnionDecl) d).textVariant() != null) {
        return (Ir.UnionDecl) d;
      }
    }
    return null;
  }

  /** Whether a value of this type can hold a generated model (and so needs a nested check). */
  private boolean mentionsModel(TypeName t) {
    if (t instanceof ParameterizedTypeName) {
      for (TypeName a : ((ParameterizedTypeName) t).typeArguments()) {
        if (mentionsModel(a)) {
          return true;
        }
      }
      return false;
    }
    if (t instanceof ClassName) {
      Ir.Decl d = planner.index.get(t);
      return d instanceof Ir.RecordDecl || d instanceof Ir.UnionDecl;
    }
    return false;
  }

  /** Emits the checks for one value's constraints (strings, numbers, lists, maps, and their items). */
  private void constraintChecks(
      CodeBlock.Builder out, TypeSpec.Builder owner, PatternNames patterns, String name, String value, TypeName type, Ir.Constraints c) {
    constraintChecks(out, owner, patterns, name, value, type, c, 0);
  }

  private void constraintChecks(
      CodeBlock.Builder out, TypeSpec.Builder owner, PatternNames patterns, String name, String value, TypeName type, Ir.Constraints c, int depth) {
    if (c == null || c.isEmpty()) {
      return;
    }
    if (c.minLength() != null) {
      out.addStatement("checks.minLength($S, $L, $L)", name, value, c.minLength());
    }
    if (c.maxLength() != null) {
      out.addStatement("checks.maxLength($S, $L, $L)", name, value, c.maxLength());
    }
    if (c.pattern() != null) {
      try {
        Pattern.compile(c.pattern());
      } catch (RuntimeException e) {
        throw new GenerationException(name + ": pattern " + c.pattern() + " isn't a Java regex: " + e.getMessage());
      }
      String field = patterns.name(c.pattern());
      if (patterns.added.add(field)) {
        owner.addField(
            FieldSpec.builder(Pattern.class, field, Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL)
                .initializer("$T.compile($S)", Pattern.class, c.pattern())
                .build());
      }
      out.addStatement("checks.pattern($S, $L, $N)", name, value, field);
    }
    if (c.minimum() != null) {
      out.addStatement("checks.minimum($S, $L, $S)", name, value, c.minimum().toPlainString());
    }
    if (c.maximum() != null) {
      out.addStatement("checks.maximum($S, $L, $S)", name, value, c.maximum().toPlainString());
    }
    if (c.exclusiveMinimum() != null) {
      out.addStatement("checks.exclusiveMinimum($S, $L, $S)", name, value, c.exclusiveMinimum().toPlainString());
    }
    if (c.minItems() != null) {
      out.addStatement("checks.minItems($S, $L, $L)", name, value, c.minItems());
    }
    if (c.maxItems() != null) {
      out.addStatement("checks.maxItems($S, $L, $L)", name, value, c.maxItems());
    }
    if (c.uniqueItems()) {
      out.addStatement("checks.uniqueItems($S, $L)", name, value);
    }
    if (c.minProperties() != null) {
      out.addStatement("checks.minProperties($S, $L, $L)", name, value, c.minProperties());
    }
    if (c.maxProperties() != null) {
      out.addStatement("checks.maxProperties($S, $L, $L)", name, value, c.maxProperties());
    }
    TypeName element = typeArgument(type, ModelPlanner.LIST, 0);
    if (c.items() != null && !c.items().isEmpty() && element != null) {
      CodeBlock.Builder inner = CodeBlock.builder();
      String item = "item" + depth;
      constraintChecks(inner, owner, patterns, "", item, element, c.items(), depth + 1);
      out.add("checks.eachItem($S, $L, $L -> {\n$>$L$<});\n", name, value, item, inner.build());
    }
    TypeName mapValue = typeArgument(type, ModelPlanner.MAP, 1);
    if (c.keys() != null && !c.keys().isEmpty() && mapValue != null) {
      CodeBlock.Builder inner = CodeBlock.builder();
      String key = "key" + depth;
      constraintChecks(inner, owner, patterns, "", key, ModelPlanner.STRING, c.keys(), depth + 1);
      out.add("checks.eachKey($S, $L, $L -> {\n$>$L$<});\n", name, value, key, inner.build());
    }
    if (c.values() != null && !c.values().isEmpty() && mapValue != null) {
      CodeBlock.Builder inner = CodeBlock.builder();
      String entry = "entry" + depth;
      constraintChecks(inner, owner, patterns, "", entry, mapValue, c.values(), depth + 1);
      out.add("checks.eachValue($S, $L, $L -> {\n$>$L$<});\n", name, value, entry, inner.build());
    }
  }

  private static TypeName typeArgument(TypeName t, ClassName raw, int index) {
    if (t instanceof ParameterizedTypeName && ((ParameterizedTypeName) t).rawType().equals(raw)) {
      return ((ParameterizedTypeName) t).typeArguments().get(index);
    }
    return null;
  }

  /** Names the compiled patterns of one record. */
  private static final class PatternNames {
    final Map<String, String> byPattern = new LinkedHashMap<>();
    final Set<String> added = new HashSet<>();

    String name(String pattern) {
      return byPattern.computeIfAbsent(pattern, p -> "PATTERN_" + byPattern.size());
    }
  }

  private static String literal(Object v) {
    if (v instanceof String) {
      return CodeBlock.of("$S", v).toString();
    }
    if (v instanceof Integer || v instanceof Long) {
      return v + "L";
    }
    return String.valueOf(v);
  }

  static CodeBlock stringList(List<String> values) {
    CodeBlock.Builder b = CodeBlock.builder().add("$T.of(", List.class);
    for (int i = 0; i < values.size(); i++) {
      b.add(i == 0 ? "$S" : ", $S", values.get(i));
    }
    return b.add(")").build();
  }

